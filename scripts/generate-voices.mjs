import { KokoroTTS } from 'kokoro-js'
import { env } from '@huggingface/transformers'
import { mkdir, readdir, readFile, writeFile, access } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { scenes, authoredBeats } from '../src/narrative/story.ts'

// Offline authoring only. Existing matching recordings are retained byte-for-byte.
env.cacheDir = './node_modules/.cache/kokoro'
const model = 'onnx-community/Kokoro-82M-v1.0-ONNX'
const tts = await KokoroTTS.from_pretrained(model, { dtype: 'q8', device: 'cpu' })
const beats = scenes.flatMap(authoredBeats)
const unique = [...new Map(beats.filter(beat => beat.performance.voiceId).map(beat => [beat.performance.voiceId, beat])).values()]
const previous = JSON.parse(await readFile('assets/dialogue-provenance.json', 'utf8')).clips
await mkdir('public/audio/dialogue', { recursive: true })
const catalog = {}
for (const beat of unique) {
  const id = beat.performance.voiceId
  const second = id.startsWith('pause-') || id.startsWith('correction-')
  const voice = beat.speaker === 'Customer' ? second ? 'bm_george' : 'af_heart' : beat.speaker === 'You' ? 'bm_daniel' : beat.speaker === 'Colleague' ? 'bf_emma' : beat.speaker === 'Manager' ? 'am_michael' : 'am_fenrir'
  const speed = beat.speaker === 'Customer' && !second ? 1.04 : 1
  const old = previous[id]
  const src = `/audio/dialogue/${id}.wav`
  if (old?.text === beat.line && old.voice === voice && await access('public' + src).then(() => true).catch(() => false)) {
    catalog[id] = { src, text: beat.line, duration: old.duration, voice }
    console.log(`${id}: retained`)
    continue
  }
  const audio = await tts.generate(beat.line, { voice, speed })
  await audio.save('public' + src)
  catalog[id] = { src, text: beat.line, duration: audio.audio.length / audio.sampling_rate, voice }
  console.log(`${id}: ${catalog[id].duration.toFixed(2)}s`)
}
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const modelDir = `node_modules/.cache/kokoro/${model}/onnx`
const modelFiles = await Promise.all((await readdir(modelDir)).map(async file => ({ file, sha256: hash(await readFile(`${modelDir}/${file}`)) })))
const clips = Object.fromEntries(await Promise.all(Object.entries(catalog).map(async ([id, clip]) => [id, { ...clip, sha256: hash(await readFile('public' + clip.src)) }])))
const metadata = { generator: 'kokoro-js 1.2.1', model, modelFiles, sources: ['https://huggingface.co/' + model, 'https://github.com/hexgrad/kokoro', 'https://www.npmjs.com/package/kokoro-js/v/1.2.1'], quantization: 'q8', sampleRate: 24000, license: 'Apache-2.0', generated: '2026-10-25', cloning: false, voiceSettings: { chapter1Customer: { voice: 'af_heart', speed: 1.04 }, chapter2And3Customer: { voice: 'bm_george', speed: 1 }, you: { voice: 'bm_daniel', speed: 1 }, colleague: { voice: 'bf_emma', speed: 1 }, manager: { voice: 'am_michael', speed: 1 }, kitchen: { voice: 'am_fenrir', speed: 1 } }, captionSha256: hash(JSON.stringify(unique.map(beat => beat.line))), clips }
await writeFile('assets/dialogue-provenance.json', JSON.stringify(metadata, null, 2) + '\n')
await writeFile('src/performance/voiceCatalog.ts', '// Generated by scripts/generate-voices.mjs. Saved local clips; no runtime synthesis.\nexport const voiceCatalog: Record<string, { src: string; text: string; duration: number; voice: string }> = ' + JSON.stringify(catalog, null, 2) + '\n')

